import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {openSettings} from './helpers';
test('appearance overrides the system and import defaults do not alter the current draft',async({page})=>{
  await page.emulateMedia({colorScheme:'dark'});await page.goto('/tests/fixture.html');
  await page.getByLabel('素材来源',{exact:true}).fill('/Volumes/EOS_DIGITAL');
  await page.getByLabel('目标文件夹',{exact:true}).fill('/current');
  await openSettings(page);await page.getByLabel('外观',{exact:true}).selectOption('light');
  await expect(page.locator('html')).toHaveAttribute('data-theme','light');
  expect(await page.evaluate(()=>getComputedStyle(document.documentElement).colorScheme)).toBe('light');
  await page.getByLabel('外观',{exact:true}).selectOption('dark');
  expect(await page.evaluate(()=>getComputedStyle(document.documentElement).colorScheme)).toBe('dark');
  await page.getByLabel('外观',{exact:true}).selectOption('system');
  await page.getByRole('tab',{name:'通用',exact:true}).focus();await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('tab',{name:'导入',exact:true})).toBeFocused();
  await page.getByRole('dialog').getByRole('button',{name:'浏览…',exact:true}).click();
  await expect(page.getByLabel('默认目标文件夹',{exact:true})).toHaveValue('/default/Camera');
  await page.getByLabel('默认预设',{exact:true}).selectOption('builtin:original');
  const notifications=page.getByLabel('导入完成后通知',{exact:true});
  await notifications.click();
  await expect(notifications).toBeChecked();
  await page.getByRole('button',{name:'发送测试通知',exact:true}).click();
  await expect(page.getByText('测试通知已提交。',{exact:true})).toBeVisible();
  await page.getByLabel('导入期间防止自动休眠',{exact:true}).uncheck();
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();expect(audit.violations.map(v=>v.id)).toEqual([]);
  await page.keyboard.press('Escape');
  await expect(page.getByLabel('目标文件夹',{exact:true})).toHaveValue('/current');
  await page.getByRole('button',{name:'扫描素材',exact:true}).click();await page.getByRole('button',{name:'继续',exact:true}).click();
  await expect(page.getByLabel('预设',{exact:true})).toHaveValue('builtin:organized');
  await page.getByRole('button',{name:'生成预览',exact:true}).click();await page.getByLabel('已确认以上提示').check();await page.getByRole('button',{name:'开始导入',exact:true}).click();
  await openSettings(page);await page.getByRole('tab',{name:'导入',exact:true}).click();await expect(page.getByLabel('导入期间防止自动休眠',{exact:true})).toBeDisabled();await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'暂停',exact:true}).click();await page.getByRole('button',{name:'继续导入',exact:true}).click();await page.getByRole('button',{name:'新建导入',exact:true}).click();
  await expect(page.getByLabel('目标文件夹',{exact:true})).toHaveValue('/default/Camera');
  await page.getByRole('button',{name:'扫描素材',exact:true}).click();await page.getByRole('button',{name:'继续',exact:true}).click();await expect(page.getByLabel('预设',{exact:true})).toHaveValue('builtin:original');
  await expect.poll(async()=>page.evaluate(()=>(globalThis as any).readSavedSettings()?.prevent_sleep)).toBe(false);
});
