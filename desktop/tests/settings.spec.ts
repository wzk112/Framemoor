for(const colorScheme of ['light','dark'] as const)test(`unchecked mode stays visible through the workflow and reports in ${colorScheme}`,async({page})=>{
  await page.emulateMedia({colorScheme});await page.setViewportSize({width:1000,height:700});await page.goto('/tests/fixture.html');
  await openSettings(page);await page.getByRole('tab',{name:'性能',exact:true}).click();
  await expect(page.getByLabel('校验文件内容（SHA-256）',{exact:true})).toBeChecked();
  await page.getByLabel('校验文件内容（SHA-256）',{exact:true}).uncheck();
  await expect(page.getByLabel('校验并发数',{exact:true})).toBeDisabled();
  await expect(page.getByRole('dialog').getByText('校验已关闭 · 可靠性降低，导入可能更快',{exact:true})).toBeVisible();
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();expect(audit.violations.map(v=>v.id)).toEqual([]);
  await page.keyboard.press('Escape');
  const banner=page.locator('.workspace > .verification-warning');
  await expect(banner).toBeVisible();
  await page.getByLabel('素材来源',{exact:true}).fill('/Volumes/EOS_DIGITAL');await page.getByLabel('目标文件夹',{exact:true}).fill('/current');
  await page.getByRole('button',{name:'扫描素材',exact:true}).click();await expect(banner).toBeVisible();
  await page.getByRole('button',{name:'继续',exact:true}).click();await expect(banner).toBeVisible();
  await page.getByRole('button',{name:'变量说明',exact:true}).click();await expect(page.getByRole('dialog').getByText('校验已关闭 · 可靠性降低，导入可能更快',{exact:true})).toBeVisible();await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'生成预览',exact:true}).click();await expect(banner).toBeVisible();await page.getByLabel('已确认以上提示').check();await page.getByRole('button',{name:'开始导入（不校验）',exact:true}).click();
  await expect(banner).toBeVisible();await expect(page.locator('.import-details').getByText('已关闭 · 未校验',{exact:true})).toBeVisible();
  await openSettings(page);await page.getByRole('tab',{name:'性能',exact:true}).click();await expect(page.getByLabel('校验文件内容（SHA-256）',{exact:true})).toBeDisabled();await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  // Global preference changes cannot relabel an existing task as verified.
  await openSettings(page);await page.getByRole('tab',{name:'性能',exact:true}).click();await page.getByLabel('校验文件内容（SHA-256）',{exact:true}).check();await page.getByRole('tab',{name:'通用',exact:true}).click();await page.getByLabel('界面语言',{exact:true}).selectOption('en');await page.keyboard.press('Escape');
  await expect(banner).toContainText('Verification off');await page.getByRole('button',{name:'Resume import',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Import complete · Not verified'}).first()).toBeVisible();await expect(page.getByRole('button',{name:'Export import report',exact:true})).toBeVisible();
  await expect(page.locator('.history')).toContainText('Not verified');
  await page.getByRole('button',{name:'New import',exact:true}).click();await expect(banner).toHaveCount(0);
});
